#include <iostream>
#include <GeographicLib/Utility.hpp>
#include <GeographicLib/EllipticFunction.hpp>

using namespace std;
using namespace GeographicLib;
typedef Math::real R;
typedef Math::cmplx C;

static int chk(R x, R y, R d) {
  if (fabs(x - y) <= d)
    return 0;
  cout << "chk fails: " << x << " != " << y << " +/- " << d << "\n";
  return 1;
}

static int chk(C x, C y, C d) {
  if (fabs(x.real() - y.real()) <= d.real() &&
      fabs(x.imag() - y.imag()) <= d.imag())
    return 0;
  cout << "chk fails: " << x << " != " << y << " +/- " << d << "\n";
  return 1;
}

int main() {
  Utility::set_digits();
  int n = 0;
  R m = 0.5e-13;
  using E = EllipticFunction;

  // The numerical checks in Carlson 1995, Sec 3.
  cout << setprecision(14);
  n+=chk(E::RF(1,2), 1.3110287771461, m);
  n+=chk(E::RF(C(1),C(2)), C(1.3110287771461,0), m*C(1,0));
  n+=chk(E::RF(0.5,1), 1.8540746773014, m);
  n+=chk(E::RF(C(0.5),C(1)), C(1.8540746773014,0), m*C(1,0));
  n+=chk(E::RF(C(0,1),C(0,-1)), C(1.8540746773014,0), m*C(1,0));
  n+=chk(E::RF(C(-1,1),C(0,1)), C(0.79612586584234,-1.2138566698365),
         m*C(.1,1));
  n+=chk(E::RF(2,3,4), 0.58408284167715, m*.1);
  n+=chk(E::RF(C(2),C(3),C(4)), C(0.58408284167715,0), m*C(.1,0));
  n+=chk(E::RF(C(0,1),C(0,-1),C(2)), C(1.0441445654064,0), m*C(1,0));
  n+=chk(E::RF(C(-1,1),C(0,1),C(1,-1)), C(0.93912050218619,-0.53296252018635),
         m*C(.1,.1));
  n+=chk(E::RC(0,0.25), 3.1415926535898, m);
  n+=chk(E::RC(C(0),C(0.25)), C(3.1415926535898,0), m*C(1,0));
  n+=chk(E::RC(2.25,2), 0.69314718055995, m*.1);
  n+=chk(E::RC(C(2.25),C(2)), C(0.69314718055995,0), m*C(.1,0));
  n+=chk(E::RC(C(0),C(0,1)), C(1.1107207345396,-1.1107207345396), m*C(1,1));
  n+=chk(E::RC(C(0,-1),C(0,1)), C(1.2260849569072,-0.34471136988768),
         m*C(1,.1));
  n+=chk(E::RC(0.25,-2), 0.23104906018665, m*.1);
  n+=chk(E::RC(C(0.25),C(-2)), C(0.23104906018665,0), m*C(.1,0));
  n+=chk(E::RC(C(0,1),C(-1)), C(0.77778596920447,0.19832484993429), m*C(.1,.1));
  n+=chk(E::RJ(0,1,2,3), 0.77688623778582, m*.1);
  n+=chk(E::RJ(C(0),C(1),C(2),C(3)), C(0.77688623778582,0), m*C(.1,0));
  n+=chk(E::RJ(2,3,4,5), 0.14297579667157, m*.1);
  n+=chk(E::RJ(C(2),C(3),C(4),C(5)), C(0.14297579667157,0), m*C(.1,0));
  n+=chk(E::RJ(C(2),C(3),C(4),C(-1,1)), C(0.13613945827771,-0.38207561624427),
         m*C(.1,.1));
  n+=chk(E::RJ(C(0,1),C(0,-1),C(0),C(2)), C(1.6490011662711,0), m*C(1,0));
  n+=chk(E::RJ(C(-1,1),C(-1,-1),C(1),C(2)), C(0.9414835884122,0), m*C(.1,0));
  n+=chk(E::RJ(C(0,1),C(0,-1),C(0),C(1,-1)), C(1.8260115229009,1.2290661908643),
         m*C(1,1));
  n+=chk(E::RJ(C(-1,1),C(-1,-1),C(1),C(-3,1)),
         C(-0.61127970812028,-1.0684038390007), m*C(.1,1));
  n+=chk(E::RJ(C(-1,1),C(-2,-1),C(0,-1),C(-1,1)),
         C(1.8249027393704,-1.2218475784827), m*C(1,1));
  n+=chk(E::RJ(2,3,4,-0.5), 0.24723819703052, m*.1);
  n+=chk(E::RJ(C(2),C(3),C(4),C(-0.5)), C(0.24723819703052,0), m*C(.1,0));
  n+=chk(E::RJ(2,3,4,-5), -0.12711230042964, m*.1);
  n+=chk(E::RJ(C(2),C(3),C(4),C(-5)), C(-0.12711230042964,0), m*C(.1,0));
  n+=chk(E::RD(0,2,1), 1.7972103521034, m);
  n+=chk(E::RD(C(0),C(2),C(1)), C(1.7972103521034,0), m*C(1,0));
  n+=chk(E::RD(2,3,4), 0.16510527294261, m*.1);
  n+=chk(E::RD(C(2),C(3),C(4)), C(0.16510527294261,0), m*C(.1,0));
  n+=chk(E::RD(C(0,1),C(0,-1),C(2)), C(0.6593385415422,0), m*C(.1,0));
  n+=chk(E::RD(C(0),C(0,1),C(0,-1)), C(1.270819627191,2.7811120159521),
         m*C(1,1));
  n+=chk(E::RD(C(0),C(-1,1),C(0,1)), C(-1.8577235439239,-0.96193450888839),
         m*C(1,.1));
  n+=chk(E::RD(C(-2,-1),C(0,-1),C(-1,1)), C(1.8249027393704,-1.2218475784827),
         m*C(1,1));
  n+=chk(E::RG(16,16), 3.1415926535898, m);
  n+=chk(E::RG(C(16),C(16)), C(3.1415926535898,0), m*C(1,0));
  n+=chk(E::RG(2,3,4), 1.7255030280692, m);
  n+=chk(E::RG(C(2),C(3),C(4)), C(1.7255030280692,0), m*C(1,0));
  n+=chk(E::RG(C(0),C(0,1),C(0,-1)), C(0.42360654239699,0), m*C(.1,0));
  n+=chk(E::RG(C(-1,1),C(0,1)), C(0.44660591677018,0.70768352357515),
         m*C(.1,.1));
  n+=chk(E::RG(C(0,-1),C(-1,1),C(0,1)), C(0.36023392184473,0.40348623401722),
         m*C(.1,.1));
  n+=chk(E::RG(0.0796,4), 1.0284758090288, m);
  n+=chk(E::RG(C(0.0796),C(4)), C(1.0284758090288,0), m*C(1,0));
  if (n) {
    cout << n << " failure" << (n > 1 ? "s" : "") << "\n";
      return 1;
  }
}
